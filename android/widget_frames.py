"""Cuts small looping frames for the home screen widget from Sparky's original 60 FPS clips."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'android/app/src/main/res/drawable-nodpi'
FRAME, COLS, PER_CHUNK, SIZE = 384, 10, 40, 192
SOURCE_FPS, WIDGET_FPS = 60, 20
# pose: (clip file name, loop start, exclusive loop end)
POSES = {'ready': ('idle', 0, 302), 'proud': ('proud', 242, 544),
         'soso': ('mixed', 0, 302), 'disappointed': ('disappointed', 0, 302)}
chunks = {}
def frame(name, index):
    chunk, offset = divmod(index, PER_CHUNK)
    key = (name, chunk)
    if key not in chunks:
        chunks[key] = Image.open(ROOT / f'public/turtle-plush-{name}-{chunk}.webp').convert('RGBA')
    row, col = divmod(offset, COLS)
    return chunks[key].crop((col * FRAME, row * FRAME, (col + 1) * FRAME, (row + 1) * FRAME))

for old in OUT.glob('sparky_anim_*.webp'):
    old.unlink()
arrays = []
for pose, (name, start, total) in POSES.items():
    length = total - start
    keep = round(length * WIDGET_FPS / SOURCE_FPS)
    items = []
    for n in range(keep):
        index = start + round(n * length / keep)
        image = frame(name, min(index, total - 1)).resize((SIZE, SIZE), Image.LANCZOS)
        file = f'sparky_anim_{pose}_{n:02d}'
        image.save(OUT / f'{file}.webp', 'WEBP', quality=88, method=2)
        items.append(f'        <item>@drawable/{file}</item>')
    seconds = keep / WIDGET_FPS
    arrays.append(f'    <!-- {keep} frames over {seconds:.1f} s -->\n    <array name="sparky_frames_{pose}">\n' + '\n'.join(items) + '\n    </array>')
    print(pose, keep, 'frames, flip every', round(seconds * 1000 / keep), 'ms')
(ROOT / 'android/app/src/main/res/values/sparky_frames.xml').write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/widget_frames.py. -->\n<resources>\n'
    + f'    <integer name="sparky_flip_interval_ms">{1000 // WIDGET_FPS}</integer>\n'
    + '\n'.join(arrays) + '\n</resources>\n', encoding='utf-8')
total = sum(p.stat().st_size for p in OUT.glob('sparky_anim_*.webp'))
print('total KB', total // 1024)
